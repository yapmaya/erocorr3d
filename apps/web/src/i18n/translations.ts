export type TranslationKey = keyof typeof dictionary;

export function translate(key: TranslationKey, locale: Locale): string {
  return dictionary[key][locale];
}

export function translateUnverifiedBadgeLabel(count: number, locale: Locale): string {
  if (locale === "tr") {
    return `⚠ Bu sonuç ${count} adet doğrulanmamış katsayı kullanıyor`;
  }
  return `⚠ This result uses ${count} unverified coefficient${count === 1 ? "" : "s"}`;
}

export function useTranslation(): {
  t: (key: TranslationKey) => string;
  locale: Locale;
} {
  const locale = useUiStore((state) => state.locale);
  return { t: (key: TranslationKey) => translate(key, locale), locale };
}
